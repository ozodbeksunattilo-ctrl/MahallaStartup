'use client';

import { useSyncExternalStore } from 'react';

/** uz — o'zbek (lotin, manba til), ru — rus, en — ingliz. Manba matnlar o'zbek lotinida yoziladi. */
export type Lang = 'uz' | 'ru' | 'en';

export const LANGS: Array<{ code: Lang; label: string }> = [
  { code: 'uz', label: 'UZ' },
  { code: 'ru', label: 'RU' },
  { code: 'en', label: 'EN' },
];

const KEY = 'mhd_lang';
let current: Lang = 'uz';
let loaded = false;
const listeners = new Set<() => void>();

function load(): void {
  if (loaded || typeof window === 'undefined') return;
  loaded = true;
  try {
    const saved = window.localStorage.getItem(KEY);
    if (saved === 'ru' || saved === 'en') current = saved;
  } catch {
    // localStorage yopiq bo'lsa (maxfiy rejim) — o'zbekcha qoladi
  }
}

export function getLang(): Lang {
  load();
  return current;
}

export function setLang(lang: Lang): void {
  load();
  if (lang === current) return;
  current = lang;
  try {
    window.localStorage.setItem(KEY, lang);
  } catch {
    // saqlanmasa ham joriy sessiyada ishlaydi
  }
  listeners.forEach((fn) => fn());
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Joriy til; til o'zgarganda komponent qayta chiziladi. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, () => 'uz');
}

